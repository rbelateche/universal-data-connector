"""Helpers shared by the deploy scripts. Secrets are never printed."""

import os
import secrets
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
ENV_FILE = BACKEND / ".env"
MCP_ENV_FILE = BACKEND.parent / "mcp-app" / ".env.deploy"


def trust_system_certificates() -> None:
    """Behind a TLS-inspecting proxy, Python's bundled CAs fail; use the OS store."""
    try:
        import truststore
    except ImportError:
        return
    truststore.inject_into_ssl()


def load_env() -> None:
    try:
        from dotenv import load_dotenv
    except ImportError:
        return
    load_dotenv(ENV_FILE)


def demo_api_key() -> str:
    """The key protecting the public demo API; generated into backend/.env once."""
    key = os.environ.get("UDC_DEMO_API_KEY")
    if key:
        return key
    key = secrets.token_urlsafe(32)
    with ENV_FILE.open("a", encoding="utf-8") as f:
        f.write("\n# Protects the public demo API (generated by the deploy scripts)\n")
        f.write(f"UDC_DEMO_API_KEY={key}\n")
    os.environ["UDC_DEMO_API_KEY"] = key
    print(f"Generated a demo API key and saved it to {ENV_FILE.name} as UDC_DEMO_API_KEY.")
    return key


def write_mcp_env(api_url: str, api_key: str, extra: dict[str, str] | None = None) -> None:
    """mcp-app/.env.deploy (gitignored), read by `alpic deploy --env-file`."""
    lines = [f"UDC_API_URL={api_url}", f"UDC_API_KEY={api_key}"]
    lines += [f"{k}={v}" for k, v in (extra or {}).items()]
    MCP_ENV_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    MCP_ENV_FILE.chmod(0o600)
    print(f"Wrote {MCP_ENV_FILE.relative_to(BACKEND.parent)} for the Alpic deploy.")
